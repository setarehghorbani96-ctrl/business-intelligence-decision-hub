-- PostgreSQL semantic layer placeholders for Business Intelligence Decision Hub
-- The following views are intentionally documented only at schema v1.
-- They will be implemented after validated source data, KPI logic, and business rules are available.

-- vw_executive_kpis
-- Future purpose: consolidate top-level leadership KPIs across finance, operations, customers, assets, and ESG.

-- vw_finance_performance
-- Future purpose: expose revenue, cost, budget variance, and margin trends by date, region, and department.

-- vw_operations_performance
-- Future purpose: expose SLA compliance, backlog, request volume, and average resolution time metrics.

-- vw_asset_performance
-- Future purpose: expose asset availability, downtime, maintenance cost, and failure patterns.

-- vw_customer_performance
-- Future purpose: expose satisfaction, complaint rate, churn risk, and contract-value analytics.

-- vw_esg_performance
-- Future purpose: expose energy, emissions, water, waste, and renewable-share KPI rollups.

-- vw_decision_recommendations
-- Future purpose: provide a curated surface for future decision-support logic and AI-generated recommendations.
